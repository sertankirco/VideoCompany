# aerender command + execution
# ---------------------------------------------------------------------------


def build_aerender_command(
    aerender_bin: str,
    project_path: str,
    comp_name: str,
    output_path: str,
    start_frame: int = 0,
    end_frame: int = 179,
    fps: int = 60,
    rs_template: str = "Best Settings",
    om_template: str = "h.264 - Match Source",
) -> list[str]:
    """
    Builds the aerender argument list.

    Motion Blur is controlled via the .aep file (set by execute_jsx before
    this call); aerender honours whatever shutterAngle is saved in the project.
    The -RStemplate "Best Settings" flag instructs aerender to use the
    composition's own render settings (which include the saved shutterAngle).

    Args:
        aerender_bin: Path to the aerender binary.
        project_path: Path to the .aep file (pre-updated by execute_jsx).
        comp_name: Name of the composition to render.
        output_path: Destination MP4 path.
        start_frame: First frame to render (default 0).
        end_frame: Last frame to render (default 179 = 3s @ 60fps).
        fps: Frames per second.
        rs_template: Render Settings template name in AE.
        om_template: Output Module template name in AE.

    Returns:
        List of strings suitable for subprocess.Popen/run.
    """
    return [
        aerender_bin,
        "-project", project_path,
        "-comp", comp_name,
        "-output", output_path,
        "-s", str(start_frame),
        "-e", str(end_frame),
        "-fps", str(fps),
        "-RStemplate", rs_template,
        "-OMtemplate", om_template,
        "-continueOnMissingFootage",
    ]


def run_render(
    aerender_bin: str,
    command: list[str],
    timeout_seconds: int = 600,
) -> int:
    """
    Executes the aerender command and streams its output to the logger.

    Args:
        aerender_bin: Path to aerender (used only for logging).
        command: The full argv list returned by build_aerender_command().
        timeout_seconds: Kill the process if it exceeds this duration.

    Returns:
        Process exit code (0 = success).

    Raises:
        subprocess.TimeoutExpired: If render exceeds timeout_seconds.
    """
    logger.info("Starting aerender: %s", " ".join(command))

    proc = subprocess.Popen(
        command,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )

    try:
        for line in proc.stdout:
            logger.info("[aerender] %s", line.rstrip())
        for line in proc.stderr:
            logger.error("[aerender:err] %s", line.rstrip())
        proc.wait(timeout=timeout_seconds)
    except subprocess.TimeoutExpired:
        proc.kill()
        raise

    if proc.returncode == 0:
        logger.info("aerender finished successfully (exit 0).")
    else:
        logger.error("aerender failed with exit code %d.", proc.returncode)

    return proc.returncode
